// Simulates the theme engine over 12 weeks with sample calendar events.
// Usage: node scripts/simulate-weeks.js > docs/checkpoint-3.md
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const E = {};
vm.createContext(E);
for (const f of ['Content.js', 'Engine.js']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../apps-script', f), 'utf8'), E);

const read = (f) => JSON.parse(fs.readFileSync(path.join(__dirname, '../content', f), 'utf8'));
const files = read('library/INDEX.json').files.map((f) => read('library/' + f));
const lib = { themes: read('themes.json'), calendar: read('default_calendar.json'), keywords: read('keywords.json'),
              entries: files.flatMap((f) => f.entries), idioms: files.flatMap((f) => f.idioms) };
const names = Object.fromEntries(lib.themes.map((t) => [t.tag, t.name_fr]));

// Sample events, as they would come from Joint Chaos and your other calendars.
const EVENTS = [
  { title: 'Weekly team standup', start: '2026-12-07', recurring: true },
  { title: 'Dentist – cleaning', start: '2026-12-10' },
  { title: 'Dinner at Sam & Alex’s', start: '2026-12-12' },
  { title: 'Office holiday party', start: '2026-12-18' },
  { title: 'Dinner at Léa’s', start: '2026-12-26' },
  { title: 'New Year’s Eve at the Martins', start: '2026-12-31' },
  { title: 'Board review', start: '2027-01-06', declined: true },
  { title: 'Flight to Paris (AF 23)', start: '2027-01-15', location: 'JFK' },
  { title: 'Mom’s birthday', start: '2027-01-20', end: '2027-01-21', allDay: true },
  { title: 'Car service – oil change', start: '2027-01-27' },
  { title: 'Presentation to leadership', start: '2027-02-03' },
  { title: 'Dentist follow-up', start: '2027-02-10' },
  { title: 'Dinner with the Martins', start: '2027-02-19' }
];

function run(available) {
  const history = [], rows = [];
  for (let i = 0; i < 12; i++) {
    const weekStart = E.enShift_('2026-11-30', 7 * i);
    const c = JSON.parse(JSON.stringify(E.chooseTheme_({ weekStart, lib, history, events: EVENTS, available })));
    history.push({ week_start: weekStart, tag: c.tag });
    rows.push(c);
  }
  return rows;
}

const full = run(null);
const today = run(E.completeTags_(lib));
const fmt = (d) => { const [y, m, dd] = d.split('-'); return `${dd}/${m}`; };
const src = (c) => (c.source === 'calendar' ? 'Calendar' : 'Default');

const out = [];
out.push('# Checkpoint 3: theme engine');
out.push('');
out.push('Generated by `node scripts/simulate-weeks.js`, using the real engine (`apps-script/Engine.js`), themes,');
out.push('default calendar and keywords. Week 1 is the week of Monday 30 November 2026.');
out.push('');
out.push('## Sample events');
out.push('');
out.push('| Date | Event | What the engine does with it |');
out.push('|---|---|---|');
const notes = {
  'Weekly team standup': 'Skipped: recurring',
  'Board review': 'Skipped: declined',
  'Mom’s birthday': 'Skipped: all-day birthday reminder'
};
for (const e of EVENTS) {
  const n = notes[e.title] || 'Matched (see table)';
  out.push(`| ${fmt(e.start)} | ${e.title} | ${n} |`);
}
out.push('');
out.push('## 12 weeks');
out.push('');
out.push('"Full library" assumes all 65 themes are written. "Today" uses only the themes complete now');
out.push(`(${E.completeTags_(lib).length}: ${[...E.completeTags_(lib)].map((t) => names[t]).join(', ')}).`);
out.push('');
out.push('| # | Week of | Full library | Source · why | Today |');
out.push('|---|---|---|---|---|');
full.forEach((c, i) => {
  const t = today[i];
  out.push(`| ${i + 1} | ${fmt(c.week_start)} | ${names[c.tag]} | ${src(c)} · ${c.why} | ${names[t.tag]} (${src(t)}) |`);
});
out.push('');
console.log(out.join('\n'));
